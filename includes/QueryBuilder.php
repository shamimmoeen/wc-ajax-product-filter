/**
 * Assembles the JOIN/WHERE clauses, id lists and table aliases that the filter
 * types use to narrow a product query.
 */
class QueryBuilder {

	/**
	 * Splits a comma-separated filter value string into an array.
	 *
	 * @param string $values The filter values.
	 *
	 * @return array
	 */
	public function get_chosen_filter_values( $values ) {
		$value_separator = ',';

		// Check if we have any string(including 0) in the url.
		if ( ! strlen( $values ) ) {
			return array();
		}

		$values_array = explode( $value_separator, $values );

		return is_array( $values_array ) ? $values_array : array();
	}

	/**
	 * We are using the same join to avoid the sorting issues.
	 *
	 * @return array
	 *
	 * @see WC_Query::append_product_sorting_table_join()
	 */
	public function get_lookup_table_data() {
		global $wpdb;

		$table = $wpdb->prefix . 'wc_product_meta_lookup';
		$alias = 'wc_product_meta_lookup';

		$join = "LEFT JOIN $table AS $alias ON $wpdb->posts.ID = $alias.product_id";

		return compact( 'join', 'alias' );
	}

	/**
	 * When filtering the products by price we set the price according to tax.
	 *
	 * @param string $min The minimum price.
	 * @param string $max The maximum price.
	 *
	 * @return array
	 */
	public function get_min_max_price_according_to_tax( $min, $max ) {
		$min = (float) $min;
		$max = (float) $max;

		/**
		 * Adjust if the store taxes are not displayed how they are stored.
		 * Kicks in when prices excluding tax are displayed including tax.
		 */
		if ( wc_tax_enabled() && 'incl' === get_option( 'woocommerce_tax_display_shop' ) && ! wc_prices_include_tax() ) {
			// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound
			$tax_class = apply_filters( 'woocommerce_price_filter_widget_tax_class', '' ); // Uses standard tax class.
			$tax_rates = \WC_Tax::get_rates( $tax_class );

			if ( $tax_rates ) {
				$min -= \WC_Tax::get_tax_total( \WC_Tax::calc_inclusive_tax( $min, $tax_rates ) );
				$max -= \WC_Tax::get_tax_total( \WC_Tax::calc_inclusive_tax( $max, $tax_rates ) );
			}
		}

		return compact( 'min', 'max' );
	}

	/**
	 * Gets the full SQL JOIN clause for the chosen filters.
	 *
	 * @return string
	 */
	public function get_join_clause() {
		$filter = new ProductFilter();

		$join = ' ' . $filter->get_full_join_clause();

		return apply_filters( 'wcapf_filter_join_clause', $join );
	}

	/**
	 * Gets the SQL WHERE clause for the given query type and filter key.
	 *
	 * @param string $query_type The query type.
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public function get_where_clause( $query_type, $filter_key ) {
		$main_query_type = wcapf()->settings->field_relations();

		$where = '';

		if ( 'and' === $main_query_type ) {
			if ( 'and' === $query_type ) {
				$where = $this->get_full_where_clause();
			} elseif ( 'or' === $query_type ) {
				$where = $this->get_where_clauses_by_other_filters( $filter_key );
			}
		} elseif ( 'or' === $main_query_type ) {
			if ( 'and' === $query_type ) {
				$where = $this->get_self_where_clause( $filter_key );
			} elseif ( 'or' === $query_type ) {
				$where = ' AND 1=1';
			}
		}

		return apply_filters( 'wcapf_filter_where_clause', $where, $query_type, $filter_key );
	}

	/**
	 * Gets the full SQL WHERE clause for the chosen filters.
	 *
	 * @return string
	 */
	public function get_full_where_clause() {
		$filter = new ProductFilter();

		return $filter->get_full_where_clause();
	}

	/**
	 * Gets the WHERE clauses generated by the other chosen filters.
	 *
	 * @param string $filter_key The current filter key.
	 *
	 * @return string
	 */
	public function get_where_clauses_by_other_filters( $filter_key ) {
		$chosen_filters = wcapf()->active_filters->chosen();

		$wheres = array();

		foreach ( $chosen_filters as $filter_type => $filter_type_filters ) {
			if ( 'filters_data' === $filter_type ) {
				continue;
			}

			foreach ( $filter_type_filters as $_filter_key => $filter ) {
				if ( $filter_key === $_filter_key ) {
					continue;
				}

				$wheres[] = $filter['where'];
			}
		}

		$query_type = wcapf()->settings->field_relations();

		return $this->combine_where_clauses( $wheres, $query_type );
	}

	/**
	 * Combines multiple WHERE clauses using the given query relation.
	 *
	 * @param array  $wheres     The WHERE clauses.
	 * @param string $query_type The query relation.
	 *
	 * @return string
	 */
	public function combine_where_clauses( $wheres, $query_type ) {
		if ( 'or' === $query_type ) {
			$separator = ' OR ';
		} else {
			$separator = ' AND ';
		}

		if ( $wheres ) {
			if ( 1 < count( $wheres ) ) {
				$sql = ' AND ( ' . implode( $separator, $wheres ) . ' )';
			} else {
				$sql = ' AND ' . implode( $separator, $wheres );
			}
		} else {
			$sql = '';
		}

		return $sql;
	}

	/**
	 * Gets the WHERE clause for the current filter only.
	 *
	 * @param string $filter_key The current filter key.
	 *
	 * @return string
	 */
	public function get_self_where_clause( $filter_key ) {
		$chosen_filters = wcapf()->active_filters->chosen();

		$wheres = array();

		foreach ( $chosen_filters as $filter_type => $filter_type_filters ) {
			if ( 'filters_data' === $filter_type ) {
				continue;
			}

			foreach ( $filter_type_filters as $_filter_key => $filter ) {
				if ( $filter_key === $_filter_key ) {
					$wheres[] = $filter['where'];
					break;
				}
			}
		}

		$query_type = wcapf()->settings->field_relations();

		return $this->combine_where_clauses( $wheres, $query_type );
	}

	/**
	 * Gets the SQL-safe featured product IDs list.
	 *
	 * @return string
	 */
	public function get_featured_product_ids_sql() {
		$ids = wc_get_featured_product_ids();

		$ids = $ids ? $ids : array( 0 );

		return $this->get_ids_sql( $ids );
	}

	/**
	 * Formats a list of ids as "(id,id,id)".
	 *
	 * @param array $ids The list of ids to format.
	 *
	 * @return string The formatted list.
	 */
	public function get_ids_sql( $ids ) {
		if ( empty( $ids ) || ! is_array( $ids ) ) {
			return '(0)';
		}

		return '(' . implode( ',', array_map( 'absint', $ids ) ) . ')';
	}

	/**
	 * Formats a list of term_taxonomy_ids as "(id,id,id)" from term ids.
	 *
	 * @param int[]  $term_ids The array of term ids.
	 * @param string $taxonomy The taxonomy name.
	 *
	 * @return string
	 */
	public function get_tt_ids_sql( $term_ids, $taxonomy ) {
		$terms = get_terms(
			array(
				'taxonomy'   => $taxonomy,
				'hide_empty' => false,
				'include'    => $term_ids,
			)
		);

		if ( $terms ) {
			$tt_ids = wp_list_pluck( $terms, 'term_taxonomy_id' );
		} else {
			$tt_ids = array( 0 );
		}

		return $this->get_ids_sql( $tt_ids );
	}

	/**
	 * Gets the SQL-safe on-sale product IDs list.
	 *
	 * @return string
	 */
	public function get_product_ids_on_sale_sql() {
		$ids = wc_get_product_ids_on_sale();

		$ids = $ids ? $ids : array( 0 );

		return $this->get_ids_sql( $ids );
	}

	/**
	 * Create a unique alias when joining on MySQL table.
	 *
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public function get_table_join_alias( $filter_key ) {
		return '`' . $filter_key . '`';
	}

	/**
	 * Create a unique alias when joining on MySQL table.
	 *
	 * @param int    $index      The index number.
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public function get_table_join_alias_for_query_type_and( $index, $filter_key ) {
		$postfix = $index + 1;

		return '`' . $filter_key . $postfix . '`';
	}
}

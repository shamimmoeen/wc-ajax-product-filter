/**
 * WCAPF_Product_Filter_Utils class.
 *
 * The SQL-building helpers now live in \WCAPF\QueryBuilder; the methods below
 * forward to it while the remaining callers are migrated.
 *
 * @since 3.0.0
 */
class WCAPF_Product_Filter_Utils {

	/**
	 * Gets the shared query builder instance.
	 *
	 * @return \WCAPF\QueryBuilder
	 */
	private static function query_builder() {
		static $query_builder = null;

		if ( null === $query_builder ) {
			$query_builder = new \WCAPF\QueryBuilder();
		}

		return $query_builder;
	}

	/**
	 * Gets the chosen filter values.
	 *
	 * @param string $values The filter values.
	 *
	 * @return array
	 */
	public static function get_chosen_filter_values( $values ) {
		return self::query_builder()->get_chosen_filter_values( $values );
	}

	/**
	 * We are using the same join to avoid the sorting issues.
	 *
	 * @return array
	 */
	public static function get_lookup_table_data() {
		return self::query_builder()->get_lookup_table_data();
	}

	/**
	 * When filtering the products by price we set the price according to tax.
	 *
	 * @param string $min The minimum price.
	 * @param string $max The maximum price.
	 *
	 * @return array
	 */
	public static function get_min_max_price_according_to_tax( $min, $max ) {
		return self::query_builder()->get_min_max_price_according_to_tax( $min, $max );
	}

	/**
	 * Gets the full SQL JOIN clause for the chosen filters.
	 *
	 * @return string
	 */
	public static function get_join_clause() {
		return self::query_builder()->get_join_clause();
	}

	/**
	 * Gets the SQL WHERE clause for the given query type and filter key.
	 *
	 * @param string $query_type The query type.
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public static function get_where_clause( $query_type, $filter_key ) {
		return self::query_builder()->get_where_clause( $query_type, $filter_key );
	}

	/**
	 * Gets the full SQL WHERE clause for the chosen filters.
	 *
	 * @return string
	 */
	public static function get_full_where_clause() {
		return self::query_builder()->get_full_where_clause();
	}

	/**
	 * Gets the WHERE clauses generated by the other chosen filters.
	 *
	 * @param string $filter_key The current filter key.
	 *
	 * @return string
	 */
	public static function get_where_clauses_by_other_filters( $filter_key ) {
		return self::query_builder()->get_where_clauses_by_other_filters( $filter_key );
	}

	/**
	 * Combines multiple WHERE clauses using the given query relation.
	 *
	 * @param array  $wheres     The WHERE clauses.
	 * @param string $query_type The query relation.
	 *
	 * @return string
	 */
	public static function combine_where_clauses( $wheres, $query_type ) {
		return self::query_builder()->combine_where_clauses( $wheres, $query_type );
	}

	/**
	 * Gets the WHERE clause for the current filter only.
	 *
	 * @param string $filter_key The current filter key.
	 *
	 * @return string
	 */
	public static function get_self_where_clause( $filter_key ) {
		return self::query_builder()->get_self_where_clause( $filter_key );
	}

	/**
	 * Gets the SQL-safe featured product IDs list.
	 *
	 * @return string
	 */
	public static function get_featured_product_ids_sql() {
		return self::query_builder()->get_featured_product_ids_sql();
	}

	/**
	 * Formats a list of ids as "(id,id,id)".
	 *
	 * @param array $ids The list of ids to format.
	 *
	 * @return string The formatted list.
	 */
	public static function get_ids_sql( $ids ) {
		return self::query_builder()->get_ids_sql( $ids );
	}

	/**
	 * Formats a list of term_taxonomy_ids as "(id,id,id)" from term ids.
	 *
	 * @param int[]  $term_ids The array of term ids.
	 * @param string $taxonomy The taxonomy name.
	 *
	 * @return string
	 */
	public static function get_tt_ids_sql( $term_ids, $taxonomy ) {
		return self::query_builder()->get_tt_ids_sql( $term_ids, $taxonomy );
	}

	/**
	 * Gets the SQL-safe on-sale product IDs list.
	 *
	 * @return string
	 */
	public static function get_product_ids_on_sale_sql() {
		return self::query_builder()->get_product_ids_on_sale_sql();
	}

	/**
	 * Create a unique alias when joining on MySQL table.
	 *
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public static function get_table_join_alias( $filter_key ) {
		return self::query_builder()->get_table_join_alias( $filter_key );
	}

	/**
	 * Create a unique alias when joining on MySQL table.
	 *
	 * @param int    $index      The index number.
	 * @param string $filter_key The filter key.
	 *
	 * @return string
	 */
	public static function get_table_join_alias_for_query_type_and( $index, $filter_key ) {
		return self::query_builder()->get_table_join_alias_for_query_type_and( $index, $filter_key );
	}

	/**
	 * Gets the user roles.
	 *
	 * @since 3.3.0
	 *
	 * @return array
	 */
	public static function get_user_roles() {
		global $wp_roles;

		$roles = isset( $wp_roles ) ? $wp_roles : new WP_Roles();

		$all_roles = $roles->get_names();

		return apply_filters( 'wcapf_user_roles', $all_roles );
	}

	/**
	 * Adjust the parent term id for hierarchy terms.
	 *
	 * @param \WCAPF\FormFilter $field_instance The field instance.
	 * @param array             $terms          The terms array.
	 *
	 * @since 4.0.0
	 *
	 * @return array
	 */
	public static function adjust_parent_id_for_hierarchy_terms( $field_instance, $terms ) {
		$modified = array();
		$taxonomy = $field_instance->taxonomy;

		foreach ( $terms as $_id => $_data ) {
			if ( ! array_key_exists( $_data['parent_id'], $terms ) ) {
				$ancestors = get_ancestors( $_id, $taxonomy );
				$parent_id = 0;

				foreach ( $ancestors as $ancestor ) {
					if ( array_key_exists( $ancestor, $terms ) ) {
						$parent_id = $ancestor;
						break;
					}
				}

				$_data['parent_id'] = $parent_id;
			}

			$modified[ $_id ] = $_data;
		}

		return $modified;
	}

	/**
	 * Prepare the form filters and return them to be used on the frontend.
	 *
	 * @param WP_Post $form The form.
	 *
	 * @since 4.0.0
	 *
	 * @return array
	 */
	public static function get_form_filters( $form ) {
		$form_data     = array();
		$form_id       = $form->ID;
		$form_settings = maybe_unserialize( $form->post_content );

		$filters = get_posts(
			array(
				'post_type'   => 'wcapf-filter',
				'post_status' => 'publish',
				'post_parent' => $form_id,
				'nopaging'    => true,
				'orderby'     => 'menu_order',
				'order'       => 'ASC',
			)
		);

		$form_data['form_id']    = $form_id;
		$form_data['form_title'] = $form->post_title;
		$form_data['settings']   = $form_settings;

		$form_filters = array();

		/**
		 * Register a hook to modify the form filter data.
		 */
		$filter_data = apply_filters( 'wcapf_form_filter_data', array(), $form_data );

		foreach ( $filters as $filter ) {
			$id    = $filter->ID;
			$field = maybe_unserialize( $filter->post_content );

			$field['form_id'] = $form_id;

			$field = wp_parse_args( $filter_data, $field );

			$form_filters[ $id ] = array(
				'id'    => $id,
				'title' => $filter->post_title,
				'key'   => $filter->post_name,
				'type'  => $filter->post_excerpt,
				'field' => $field,
			);
		}

		$form_data['filters'] = $form_filters;

		return $form_data;
	}
}
